-- ============================================================
-- Исправление: убрать email из поля phone в profiles
-- Поле phone должно быть NULL пока пользователь не укажет реальный номер
-- Запустить в Supabase SQL Editor
-- ============================================================

-- Очищаем phone у записей где туда был записан email (содержит @)
UPDATE public.profiles
SET phone = NULL
WHERE phone LIKE '%@%';
